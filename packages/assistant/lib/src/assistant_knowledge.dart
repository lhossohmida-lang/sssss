  /// موضوعات هذا الدور.
  static List<KnowledgeTopic> forRole(UserRole role) {
    final staff = role == UserRole.owner || role == UserRole.worker;
    return [
      for (final topic in topics)
        if (staff || !topic.staffOnly) topic,
    ];
  }

  /// نص «الرموز والقيم» من تعدادات النظام نفسها فلا ينحرف عن الشيفرة.
  static String codes() {
    String list(Iterable<(String, String)> pairs) =>
        pairs.map((p) => '${p.$1} = ${p.$2}').join('، ');
    return [
      'حضور التلميذ (attendance.status): ${list([for (final v in AttendanceStatus.values) (v.code, v.label)])}.',
      'حالة الحصة (sessions.status): ${list([for (final v in SessionStatus.values) (v.code, v.label)])}.',
      'نوع الدفعة (payments.type): ${list([for (final v in PaymentType.values) (v.code, v.label)])}.',
      'التخفيض (group_students.discount_type): ${list([for (final v in DiscountType.values) (v.code, v.label)])}.',
      'حالة الرسالة (sms_queue.status): ${list([for (final v in SmsStatus.values) (v.code, v.label)])}.',
      'نوع طلب الأستاذ (session_requests.type): ${list([for (final v in SessionRequestType.values) (v.code, v.label)])}.',
      'حالة الطلب (session_requests.status): ${list([for (final v in SessionRequestStatus.values) (v.code, v.label)])}.',
      'يوم العامل (worker_attendance.override_kind): ${list([for (final v in WorkDayKind.values) (v.code, v.label)])}.',
    ].join('\n');
  }
